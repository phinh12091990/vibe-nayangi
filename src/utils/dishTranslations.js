export function getLocalizedDishName(dishName, lang = 'vi') {
  if (!dishName) return '';
  if (lang === 'vi') return dishName;
  if (DISH_NAMES[dishName]) {
    return DISH_NAMES[dishName].en;
  }
  return dishName;
}

export function getLocalizedNutrition(nutrition, lang = 'vi') {
  if (lang === 'vi') return nutrition;
  switch (nutrition) {
    case 'Thịt đỏ': return 'Red Meat';
    case 'Thịt trắng': return 'Poultry';
    case 'Cá': return 'Seafood';
    case 'Rau củ': return 'Veggies';
    case 'Tinh bột': return 'Carbs';
    default: return nutrition;
  }
}

